export function getTranslations(lang: Language): Translations {
  return translations[lang];
}

export function t(translations: Translations, path: string, vars?: Record<string, string | number>): string {
  const keys = path.split(".");
  let value: any = translations;
  for (const key of keys) {
    if (key === "__proto__" || key === "constructor" || key === "prototype") return path;
    value = value != null && Object.hasOwn(value, key) ? value[key] : undefined;
  }
  if (typeof value !== "string") return path;
  if (vars) {
    return Object.entries(vars).reduce(
      (str, [k, v]) => str.replace(new RegExp(`\\{\\{${k}\\}\\}`, "g"), String(v)),
      value
    );
  }
  return value;
}
